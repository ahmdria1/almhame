import { execSync } from "child_process";
import { existsSync, readdirSync, readFileSync, statSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { traceRules } from "./trace-rules.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");

// The seed commit names a tool in its author and README. Origin history stays
// as it is, so CI checks only the commits after this one.
export const HISTORY_BASELINE = "48c8c50762c044a8cd76b70e354912db85fa4654";

const metaRules = [
  { name: "cursor", re: /\bcursor\b/i },
  { name: "cursor-email", re: /noreply@cursor\.com/i },
  { name: "cloud-agent", re: /cloud agent/i },
  { name: "created-by", re: /created by/i },
  { name: "generated-by", re: /generated by/i },
];

const CSS_CURSOR_UTILITY =
  /\bcursor-(?:pointer|default|auto|wait|text|move|not-allowed|grab|grabbing|zoom-in|zoom-out|none|crosshair|help|progress|cell|copy|alias|context-menu|col-resize|row-resize|nesw-resize|nwse-resize|ew-resize|ns-resize|n-resize|s-resize|e-resize|w-resize|all-scroll|no-drop|vertical-text)\b/gi;

function lockfile(filePath) {
  return /(?:^|\/)(?:pnpm-lock\.yaml|package-lock\.json|yarn\.lock)$/.test(filePath);
}

export function scrubAllowed(line, filePath = "") {
  let text = line;
  CSS_CURSOR_UTILITY.lastIndex = 0;
  if (!/\bCursor\b|cloud agent|chatgpt|openai|anthropic|\bclaude\b|copilot|\bdevin\b|gpt-[0-9]/i.test(text)) {
    text = text.replace(/created by Ahmed Alamrani/gi, "");
  }
  if (lockfile(filePath)) text = text.replace(/(^|[\s"'/@])[\w.+-]*cursor[\w.+-]*/gi, "$1");
  text = text.replace(CSS_CURSOR_UTILITY, "");
  text = text.replace(/['"]cursor['"]\s*:/gi, "");
  text = text.replace(/\bcursor\s*:\s*[^;}\n]*/gi, "");
  text = text.replace(/created by a development version of React/gi, "");
  text = text.replace(/\b(?:let|const|var)\s+cursor\b/g, "");
  text = text.replace(/\bcursor\s*=/g, "");
  text = text.replace(/\bslice\(\s*cursor\b/g, "slice(");
  text = text.replace(/\(\s*cursor\s*[,)]/g, "(");
  return text;
}

export function findViolations(line, filePath = "") {
  const text = scrubAllowed(line, filePath);
  const hits = [];
  for (const rule of traceRules) {
    if (rule.test(text)) hits.push(rule.source);
  }
  for (const rule of metaRules) {
    if (rule.re.test(text)) hits.push(rule.name);
  }
  return hits;
}

function consider(hits, label, text, filePath = "") {
  const lines = text.split("\n");
  for (let index = 0; index < lines.length; index += 1) {
    const found = findViolations(lines[index], filePath);
    if (found.length) hits.push(`${label}:${index + 1}`);
  }
}

function walk(dir, acc) {
  if (!existsSync(dir)) return acc;
  for (const name of readdirSync(dir)) {
    if (name === "cache" || name === "node_modules") continue;
    const full = path.join(dir, name);
    const stat = statSync(full);
    if (stat.isDirectory()) walk(full, acc);
    else if (stat.size <= 4_000_000 && !full.endsWith(".map")) acc.push(full);
  }
  return acc;
}

function git(args) {
  return execSync(`git ${args}`, { cwd: root, encoding: "utf8", maxBuffer: 64_000_000 });
}

function commitRecords(range) {
  const log = git(`log ${range} --format=%H%x1f%an%x1f%ae%x1f%cn%x1f%ce%x1f%s%x1f%b%x1e`);
  const records = [];
  for (const record of log.split("\x1e")) {
    const trimmed = record.trim();
    if (!trimmed) continue;
    const parts = trimmed.split("\x1f");
    const [hash, author, authorEmail, committer, committerEmail, subject] = parts;
    records.push({
      hash,
      author,
      authorEmail,
      committer,
      committerEmail,
      subject,
      body: parts.slice(6).join("\x1f"),
    });
  }
  return records;
}

function historicalDocs(hash) {
  let listed = "";
  try {
    listed = git(`ls-tree -r --name-only ${hash}`);
  } catch {
    return [];
  }
  return listed.split("\n").filter((rel) => rel === "README.md" || rel.startsWith("docs/"));
}

function showFile(hash, rel) {
  try {
    return git(`show ${hash}:${rel}`);
  } catch {
    return "";
  }
}

export function scanHistory(range) {
  const hits = [];
  for (const commit of commitRecords(range)) {
    const label = `commit ${commit.hash.slice(0, 12)}`;
    consider(hits, `${label} author`, `${commit.author} ${commit.authorEmail}`);
    consider(hits, `${label} committer`, `${commit.committer} ${commit.committerEmail}`);
    consider(hits, `${label} message`, `${commit.subject}\n${commit.body || ""}`);
    for (const rel of historicalDocs(commit.hash)) {
      consider(hits, `${label} ${rel}`, showFile(commit.hash, rel), rel);
    }
  }
  return hits;
}

function scanTree(hits) {
  const tracked = git("ls-files -z").split("\0").filter(Boolean);
  const skip = /^(scripts\/ci\/|.*\.(ttf|woff2?|png|jpg|jpeg|webp|gif|pdf|zip)$)/;
  for (const rel of tracked) {
    if (skip.test(rel)) continue;
    const full = path.join(root, rel);
    if (!existsSync(full) || statSync(full).size > 4_000_000) continue;
    consider(hits, rel, readFileSync(full, "utf8"), rel);
  }
  for (const rel of ["apps/api/dist", "apps/web/.next/static", "apps/web/.next/server", "apps/admin/.next/static", "apps/admin/.next/server"]) {
    for (const full of walk(path.join(root, rel), [])) {
      consider(hits, path.relative(root, full), readFileSync(full, "utf8"), path.relative(root, full));
    }
  }
}

function main() {
  const useBaseline = process.argv.includes("--baseline");
  const range = useBaseline ? `${HISTORY_BASELINE}..HEAD` : "HEAD";
  const hits = scanHistory(range);
  scanTree(hits);
  if (hits.length) {
    console.error(hits.slice(0, 40).join("\n"));
    console.error(`${hits.length} tool trace(s)`);
    process.exit(1);
  }
  const scope = useBaseline ? `commits after ${HISTORY_BASELINE.slice(0, 12)}` : "full history";
  console.log(`no tool traces in source, ${scope}, or build output`);
}

const invoked = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invoked) main();
