import { spawnSync } from "child_process";
import test from "node:test";
import assert from "node:assert/strict";
import { fileURLToPath } from "url";
import { HISTORY_BASELINE, findViolations } from "./check-traces.mjs";

const root = fileURLToPath(new URL("../..", import.meta.url));

function runScan(args) {
  return spawnSync(process.execPath, ["scripts/ci/check-traces.mjs", ...args], { cwd: root, encoding: "utf8" });
}

test("allows css cursor, pagination variables, and lockfile package names", () => {
  assert.deepEqual(findViolations("  cursor: pointer;", "app.css"), []);
  assert.deepEqual(findViolations("'cursor':[{'cursor':[_0x176c24(0x2b7)]", "bundle.js"), []);
  assert.deepEqual(
    findViolations("Failed to read a RSC payload created by a development version of React on the server", "react.js"),
    [],
  );
  assert.deepEqual(findViolations('className="min-h-12 cursor-pointer list-none"', "page.tsx"), []);
  assert.deepEqual(findViolations("let cursor = 0;", "query.ts"), []);
  assert.deepEqual(findViolations("const cursor = page.next;", "query.ts"), []);
  assert.deepEqual(findViolations("rows.slice(cursor, hit.from)", "query.ts"), []);
  assert.deepEqual(findViolations("  cli-cursor@2.1.0:", "pnpm-lock.yaml"), []);
  assert.deepEqual(findViolations("      restore-cursor: 2.0.0", "pnpm-lock.yaml"), []);
  assert.deepEqual(findViolations("created by Ahmed Alamrani.", "README.md"), []);
});

test("rejects tool attribution in names, emails, and sentences", () => {
  for (const line of [
    "Cursor",
    "Author: Cursor <noreply@cursor.com>",
    "This repo was created by a Cursor cloud agent.",
    "generated by a model",
    "chatgpt wrote this",
  ]) {
    assert.ok(findViolations(line, "README.md").length > 0, line);
  }
});

test("the published baseline is the seed commit", () => {
  assert.equal(HISTORY_BASELINE, "48c8c50762c044a8cd76b70e354912db85fa4654");
});

test("full history fails and the baseline scan passes", () => {
  const full = runScan([]);
  assert.notEqual(full.status, 0);
  assert.match(`${full.stdout}\n${full.stderr}`, /48c8c50762c0/);
  const baseline = runScan(["--baseline"]);
  assert.equal(baseline.status, 0, baseline.stderr);
});
